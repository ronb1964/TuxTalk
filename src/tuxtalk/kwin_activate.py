"""Bring an app's window forward on KDE, for "open Firefox" with Firefox
already open (app_focus.py).

KWin offers no D-Bus call to activate a window by its app. A KWin script can:
it sees every window, and setting workspace.activeWindow does what a click
in the task manager does (switching virtual desktop if need be). So each
attempt loads a short script that looks for the app's window, brings it
forward, and says over D-Bus whether it found one.

The answer comes to a private bus connection made for that attempt and
gone right after: the dictation service owns no bus name of its own (the
tray has TuxTalk's), a connection's unique name is enough to call, and an
answer from an earlier, slower script goes to a connection already closed
instead of counting for this one. The connection has its own main context,
waited on by the thread that asks, so GTK's loop is never involved.

Plasma 6's scripting names only (workspace.activeWindow, as kwin_focus's
script uses); on Plasma 5 the script finds no window and the app is started.
"""
import json
import logging
import os

from gi.repository import Gio, GLib

from . import kwin_focus
from .kwin_focus import load_and_start

log = logging.getLogger(__name__)

SCRIPT_PLUGIN_NAME = "tuxtalk-activate"

ANSWER_PATH = "/io/github/ronb1964/TuxTalk/AppFocus"
ANSWER_INTERFACE = "io.github.ronb1964.TuxTalk.AppFocus"
_ANSWER_XML = f"""<node>
  <interface name="{ANSWER_INTERFACE}">
    <method name="Answer">
      <arg type="b" direction="in" name="had_window"/>
    </method>
    <method name="Failed">
      <arg type="s" direction="in" name="error"/>
    </method>
  </interface>
</node>"""


def script_path(name: str) -> str:
    """Where the script *name* is written: loadScript takes a file."""
    from .config import get_data_dir

    return os.path.join(get_data_dir(), "kwin", name)


# The test every KWin script of ours applies to a window w to know it as the
# app's: a normal window (not a menu or tooltip) whose menu entry is
# desktopFile or whose class, lowercased, is in classes.
WINDOW_IS_THE_APPS_JS = """w.normalWindow && !w.deleted && (w.desktopFileName === desktopFile
                    || classes.indexOf(String(w.resourceClass).toLowerCase()) >= 0)"""


def build_script(desktop_file: str, classes, reply_to: str) -> str:
    """The KWin script: bring forward the topmost normal window whose menu
    entry is *desktop_file* ("org.kde.konsole") or whose class, lowercased,
    is one of *classes*, then answer to the connection *reply_to*.

    Every value goes in through json.dumps: a menu entry's name comes from a
    file anyone can install. A failure inside the script still answers
    (false), so TuxTalk starts the app at once rather than after the wait.
    """
    return f"""// Generated by TuxTalk for "open" said by voice: brings the app's window
// forward if it has one. Unloaded straight after; safe to delete.
(function () {{
    var desktopFile = {json.dumps(desktop_file)};
    var classes = {json.dumps(sorted(classes))};
    var found = null;
    try {{
        // Plasma 5 has neither name: nothing found, and the app is started.
        var windows = workspace.activeWindow === undefined ? [] : workspace.stackingOrder || [];
        // From the top of the stack: the window of the app used last.
        for (var i = windows.length - 1; i >= 0 && !found; i--) {{
            var w = windows[i];
            if ({WINDOW_IS_THE_APPS_JS}) {{
                found = w;
            }}
        }}
        if (found) {{
            found.minimized = false;
            workspace.activeWindow = found;
        }}
    }} catch (e) {{
        found = null;
    }}
    callDBus({json.dumps(reply_to)}, "{ANSWER_PATH}", "{ANSWER_INTERFACE}", "Answer",
             found !== null);
}})();
"""


class _Answer:
    """The private session-bus connection the script answers on (see the
    module's docstring), taking calls only while wait() runs. A script that
    failed may say so (Failed) instead of answering."""

    def __init__(self):
        """Connect and serve the Answer and Failed methods. Raises GLib.Error
        when the session bus can't be reached."""
        self.had_window = None
        self.error = None
        self._context = GLib.MainContext()
        # A registered object's calls are handed to the main context that is
        # the thread's default when it is registered.
        self._context.push_thread_default()
        try:
            address = Gio.dbus_address_get_for_bus_sync(Gio.BusType.SESSION, None)
            self._bus = Gio.DBusConnection.new_for_address_sync(
                address, Gio.DBusConnectionFlags.AUTHENTICATION_CLIENT
                | Gio.DBusConnectionFlags.MESSAGE_BUS_CONNECTION, None, None)
            interface = Gio.DBusNodeInfo.new_for_xml(_ANSWER_XML).interfaces[0]
            # GLib 2.84 deprecates register_object for this; older GLib
            # (Ubuntu 22.04's 2.72) has only register_object.
            register = getattr(self._bus, "register_object_with_closures2",
                               self._bus.register_object)
            register(ANSWER_PATH, interface, self._on_answer, None, None)
        finally:
            self._context.pop_thread_default()

    @property
    def name(self) -> str:
        """The connection's unique name, which the script calls."""
        return self._bus.get_unique_name()

    def _on_answer(self, _bus, _sender, _path, _interface, method, parameters, invocation):
        if method == "Failed":
            self.error = str(parameters.unpack()[0])
        else:
            self.had_window = bool(parameters.unpack()[0])
        invocation.return_value(None)

    def wait(self, timeout: float):
        """The script's answer, waiting up to *timeout* seconds; None when
        none came, or when it said it failed (error)."""
        expired = []
        timer = GLib.timeout_source_new(max(1, int(timeout * 1000)))
        timer.set_callback(lambda *_: expired.append(True))
        timer.attach(self._context)
        try:
            while self.had_window is None and self.error is None and not expired:
                self._context.iteration(True)
        finally:
            timer.destroy()
        return self.had_window

    def close(self):
        self._bus.close_sync(None)


def _unload(bus, plugin_name: str) -> None:
    try:
        bus.call("unloadScript", plugin_name)
    except Exception as e:      # KWin didn't answer; the next attempt unloads it first
        log.info("Could not unload the KWin script %s: %s", plugin_name, e)


def ask(build, plugin_name: str, path: str, timeout: float) -> bool | None:
    """Run a KWin script and return what it answers within *timeout* seconds
    of starting: True or False, or None when it didn't answer in time; each
    D-Bus call to KWin has kwin_focus.DBUS_TIMEOUT_S besides. *build* makes the script from the
    name of the connection to answer to; it is written to *path* and loaded
    as *plugin_name*, and taken out of KWin afterwards. Raises when KWin
    refuses the script, or RuntimeError when the script says it failed."""
    bus = kwin_focus.session_bus()
    answer = _Answer()
    try:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(build(answer.name))
        # A script left by an attempt that stopped halfway would make
        # loadScript refuse this one.
        _unload(bus, plugin_name)
        load_and_start(bus, path, plugin_name)
        had_window = answer.wait(timeout)
        if answer.error is not None:
            raise RuntimeError(f"KWin's {plugin_name} script failed: {answer.error}")
        if had_window is None:
            log.info("KWin didn't answer the %s script in time", plugin_name)
            return None
        return bool(had_window)
    finally:
        _unload(bus, plugin_name)
        answer.close()


def activate(desktop_file: str, classes, timeout: float) -> bool:
    """Bring forward the app's window (build_script says which). True when
    KWin said it had one within *timeout* seconds of starting the script.
    Raises when KWin refuses the script."""
    return bool(ask(lambda reply_to: build_script(desktop_file, classes, reply_to),
                    SCRIPT_PLUGIN_NAME, script_path("tuxtalk-activate.js"), timeout))
