"""Close, minimize and maximize windows on KDE, for the voice commands
"close Firefox", "minimize window" and so on.

Like kwin_activate.py, a short KWin script does it: it sees every window,
and closeWindow() asks the app to close as its own close button would (the
app may ask to save first), never kills it. The script answers over D-Bus
whether it found a window to act on (kwin_activate.ask runs it and waits),
or that it failed, which is not the same as finding none.
"""
import json

from . import kwin_activate

SCRIPT_PLUGIN_NAME = "tuxtalk-windows"

# What each action does to a window w in the script.
_ACTIONS = {
    "close": "w.closeWindow();",
    "minimize": "w.minimized = true;",
    "maximize": "w.setMaximize(true, true);",
    "unmaximize": "w.setMaximize(false, false);",
}


def build_script(action: str, desktop_file: str, classes, every: bool, reply_to: str) -> str:
    """The KWin script: do *action* ("close", "minimize", "maximize" or
    "unmaximize") to the app's windows, matched as kwin_activate matches
    them: the topmost one, or every one with *every*. With no
    *desktop_file* and no *classes* it acts on the active window instead,
    an app's window or its dialog, never the desktop or a panel. It answers
    to the connection *reply_to* whether it acted on any.

    Every value goes in through json.dumps: a menu entry's name comes from
    a file anyone can install. A failure inside the script is told as one
    (Failed), so it isn't taken for an app with no window.
    """
    return f"""// Generated by TuxTalk for a window command said by voice. Unloaded
// straight after; safe to delete.
(function () {{
    var desktopFile = {json.dumps(desktop_file)};
    var classes = {json.dumps(sorted(classes))};
    var every = {json.dumps(every)};
    var reply = {json.dumps(reply_to)};
    var targets = [];
    try {{
        var windows = workspace.stackingOrder || [];
        if (desktopFile === "" && classes.length === 0) {{
            var active = workspace.activeWindow;
            if (active && (active.normalWindow || active.dialog) && !active.deleted) {{
                targets.push(active);
            }}
        }} else {{
            // From the top of the stack: the window of the app used last.
            for (var i = windows.length - 1; i >= 0 && (every || targets.length === 0); i--) {{
                var w = windows[i];
                if ({kwin_activate.WINDOW_IS_THE_APPS_JS}) {{
                    targets.push(w);
                }}
            }}
        }}
        // Collected first: closing a window changes the stack.
        targets.forEach(function (w) {{
            {_ACTIONS[action]}
        }});
    }} catch (e) {{
        callDBus(reply, "{kwin_activate.ANSWER_PATH}", "{kwin_activate.ANSWER_INTERFACE}",
                 "Failed", String(e));
        return;
    }}
    callDBus(reply, "{kwin_activate.ANSWER_PATH}", "{kwin_activate.ANSWER_INTERFACE}",
             "Answer", targets.length > 0);
}})();
"""


def act(action: str, desktop_file: str, classes, every: bool, timeout: float) -> bool:
    """Do *action* to the app's windows or the active one (build_script
    says which). True when KWin acted on a window within *timeout*
    seconds. Raises when KWin refuses the script or it fails."""
    return kwin_activate.ask(
        lambda reply_to: build_script(action, desktop_file, classes, every, reply_to),
        SCRIPT_PLUGIN_NAME, kwin_activate.script_path("tuxtalk-windows.js"), timeout)
