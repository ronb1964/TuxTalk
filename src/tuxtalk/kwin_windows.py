"""Close, minimize and maximize windows on KDE, for the voice commands
"close Firefox", "minimize window" and so on.

Like kwin_activate.py, a short KWin script does it: it sees every window,
and closeWindow() asks the app to close as its own close button would (the
app may ask to save first), never kills it. The script answers over D-Bus
whether it found a window to act on (kwin_activate.ask runs it and waits),
or that it failed, which is not the same as finding none.
"""
import json

from . import kwin_activate

SCRIPT_PLUGIN_NAME = "tuxtalk-windows"

# What each action does to a window w in the script.
_ACTIONS = {
    # Nothing done: only whether the app has a window (window_actions).
    "find": "",
    "close": "w.closeWindow();",
    "minimize": "w.minimized = true;",
    # A named app's window also comes forward: said from another window.
    "maximize": "w.setMaximize(true, true); if (named) { workspace.activeWindow = w; }",
    "unmaximize": "w.setMaximize(false, false);",
    # Named apps only: brings back a minimized or maximized window.
    "restore": "w.minimized = false; w.setMaximize(false, false);"
               " workspace.activeWindow = w;",
}


def build_script(action: str, desktop_file: str, classes, every: bool, reply_to: str,
                 window: str = "") -> str:
    """The KWin script: do *action* ("close", "minimize", "maximize",
    "unmaximize" or "restore"; "find" only looks, touching no window) to the app's
    windows, matched as kwin_activate matches them: the topmost one, or
    every one with *every*. With no
    *desktop_file* and no *classes* it acts on the active window instead,
    an app's window or its dialog, never the desktop or a panel; with
    *window*, KWin's internalId of the window the command was heard in, on
    that window, active or not: the focus can move to another while KWin
    loads the script. It answers to the connection *reply_to* whether it
    acted on any.

    Every value goes in through json.dumps: a menu entry's name comes from
    a file anyone can install. A failure inside the script is told as one
    (Failed), so it isn't taken for an app with no window.
    """
    return f"""// Generated by TuxTalk for a window command said by voice. Unloaded
// straight after; safe to delete.
(function () {{
    var desktopFile = {json.dumps(desktop_file)};
    var classes = {json.dumps(sorted(classes))};
    var every = {json.dumps(every)};
    var reply = {json.dumps(reply_to)};
    var heardIn = {json.dumps(window)};
    var named = desktopFile !== "" || classes.length > 0;
    var targets = [];
    try {{
        var windows = workspace.stackingOrder || [];
        if (!named) {{
            var active = workspace.activeWindow;
            if (heardIn !== "") {{
                active = windows.filter(function (w) {{
                    return String(w.internalId) === heardIn;
                }})[0];
            }}
            if (active && (active.normalWindow || active.dialog) && !active.deleted) {{
                targets.push(active);
            }}
        }} else {{
            // From the top of the stack: the window of the app used last.
            for (var i = windows.length - 1; i >= 0 && (every || targets.length === 0); i--) {{
                var w = windows[i];
                if ({kwin_activate.WINDOW_IS_THE_APPS_JS}) {{
                    targets.push(w);
                }}
            }}
        }}
        // Collected first: closing a window changes the stack.
        targets.forEach(function (w) {{
            {_ACTIONS[action]}
        }});
    }} catch (e) {{
        callDBus(reply, "{kwin_activate.ANSWER_PATH}", "{kwin_activate.ANSWER_INTERFACE}",
                 "Failed", String(e));
        return;
    }}
    callDBus(reply, "{kwin_activate.ANSWER_PATH}", "{kwin_activate.ANSWER_INTERFACE}",
             "Answer", targets.length > 0);
}})();
"""


def act(action: str, desktop_file: str, classes, every: bool, timeout: float,
        window: str = "") -> bool:
    """Do *action* to the app's windows or the active one (build_script
    says which, and what *window* is). True when KWin acted on a window,
    False when it found none. Raises when KWin refuses the script or it
    fails, and TimeoutError when it doesn't answer within *timeout* seconds:
    the script may have run all the same, so that is never "no window"."""
    answer = kwin_activate.ask(
        lambda reply_to: build_script(action, desktop_file, classes, every, reply_to, window),
        SCRIPT_PLUGIN_NAME, kwin_activate.script_path("tuxtalk-windows.js"), timeout)
    if answer is None:
        raise TimeoutError("KWin didn't answer in time")
    return answer
