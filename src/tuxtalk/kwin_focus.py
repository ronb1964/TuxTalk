"""Report the focused window to TuxTalk on KDE, the way the extension does on GNOME.

Paste keys off which window has focus: it sends Ctrl+Shift+V to terminals (they
treat plain Ctrl+V as readline's quoted-insert and show nothing), and routes
Electron apps that swallow synthetic paste to a typing fallback. Floating
messages and the follow-window indicator need where that window is. Both are
cached by the D-Bus service (SetFocusedWindow, SetFocusedWindowGeometry),
and on KDE nothing else fills that cache.

KWin has no D-Bus property for the active window — queryWindowInfo() asks the
user to click one, and getWindowInfo() needs a UUID you do not have. The usable
route is a KWin script: it runs inside KWin, can read workspace.activeWindow, and
can call back out over D-Bus. So this loads a small script that pushes
resourceClass, internalId (which window it is) and the frame into the same
methods the extension calls, leaving everything downstream untouched.

Checked against Plasma 6.7.4 on Wayland: with the script loaded, the cache
follows focus from window to window.

Nothing here may be fatal. A missing KWin, a refused call or an unwritable data
directory costs the paste hint; it must never cost the tray.
"""

import os

from . import desktop_detect
from .dbus_service import DBUS_INTERFACE, DBUS_NAME, DBUS_PATH
from .logger import setup_logger

logger = setup_logger(__name__)

# KWin identifies loaded scripts by this name; unloading uses it too.
SCRIPT_PLUGIN_NAME = "tuxtalk-focus"
# Its name before the 0.15.0 rename; a TalkType run may have left it loaded.
OLD_SCRIPT_PLUGIN_NAMES = ("talktype-focus",)

KWIN_SERVICE = "org.kde.KWin"
KWIN_SCRIPTING_PATH = "/Scripting"
KWIN_SCRIPTING_INTERFACE = "org.kde.kwin.Scripting"


def script_path() -> str:
    """Where the KWin script is written.

    It has to be a real file: loadScript takes a path, and KWin reads it. The
    data directory is stable across runs, unlike an AppImage's mount point.
    """
    from .config import get_data_dir

    return os.path.join(get_data_dir(), "kwin", "tuxtalk-focus.js")


def build_script() -> str:
    """The KWin script source.

    Reports on every focus change AND once at load, so the hint is right
    immediately rather than only after the user switches windows.
    """
    return f"""// Generated by TuxTalk. Reports the focused window so paste can
// choose Ctrl+Shift+V for terminals, and where it is, so TuxTalk's messages
// can show over it. Safe to delete; it is rewritten at startup.
var tuxtalkWatched = null;

function tuxtalkNumbers(g) {{
    return [g.x, g.y, g.width, g.height].map(Math.round).join(",");
}}

// "x,y,w,h|output|ox,oy,ow,oh": the window's frame and its screen (window_geometry.py).
function tuxtalkFrame(w) {{
    if (!w || !w.frameGeometry) {{
        return "";
    }}
    var o = w.output;
    return tuxtalkNumbers(w.frameGeometry) + "|" + ((o && o.name) ? String(o.name) : "") +
        "|" + ((o && o.geometry) ? tuxtalkNumbers(o.geometry) : "0,0,0,0");
}}

function tuxtalkGeometry() {{
    callDBus("{DBUS_NAME}",
             "{DBUS_PATH}",
             "{DBUS_INTERFACE}",
             "SetFocusedWindowGeometry",
             tuxtalkFrame(workspace.activeWindow));
}}

// A drag or resize changes the frame on every frame: report once it ends.
function tuxtalkGeometryChanged() {{
    var w = tuxtalkWatched;
    if (w && (w.move || w.resize)) {{
        return;
    }}
    tuxtalkGeometry();
}}

function tuxtalkReport(w) {{
    var cls = (w && w.resourceClass) ? String(w.resourceClass) : "";
    // Its class, which window it is and where, in one call: two windows of
    // one app look the same by their class (focused_window.py), and a look
    // between separate calls would pair one window's class with another's id.
    callDBus("{DBUS_NAME}",
             "{DBUS_PATH}",
             "{DBUS_INTERFACE}",
             "SetFocusedWindow",
             cls,
             (w && w.internalId) ? String(w.internalId) : "",
             tuxtalkFrame(w));
    // Follow this window's moves and resizes until another one is active.
    if (tuxtalkWatched && tuxtalkWatched.frameGeometryChanged) {{
        try {{ tuxtalkWatched.frameGeometryChanged.disconnect(tuxtalkGeometryChanged); }} catch (e) {{}}
    }}
    if (tuxtalkWatched && tuxtalkWatched.interactiveMoveResizeFinished) {{
        try {{ tuxtalkWatched.interactiveMoveResizeFinished.disconnect(tuxtalkGeometry); }} catch (e) {{}}
    }}
    tuxtalkWatched = w;
    if (w && w.frameGeometryChanged) {{
        w.frameGeometryChanged.connect(tuxtalkGeometryChanged);
    }}
    if (w && w.interactiveMoveResizeFinished) {{
        w.interactiveMoveResizeFinished.connect(tuxtalkGeometry);
    }}
}}

if (workspace.windowActivated) {{
    workspace.windowActivated.connect(tuxtalkReport);
}}

tuxtalkReport(workspace.activeWindow);
"""


# KWin answers in milliseconds; this only bounds a wedged compositor. For
# kwin_hotkeys' calls too.
DBUS_TIMEOUT_S = 3.0


def session_bus():
    """A .call(method, *args) shim over KWin's Scripting interface.

    dbus is imported here rather than at module scope so this module stays
    importable (and testable) without dbus-python present.
    """
    import dbus

    bus = dbus.SessionBus()

    # KWin publishes loadScript twice — (path) and (path, pluginName). Without
    # an explicit signature dbus-python matches the one-argument overload and
    # rejects the call, so the plugin name (which unloadScript needs later) has
    # to be spelled out here.
    signatures = {"loadScript": "ss", "unloadScript": "s", "start": ""}

    class _KWinBus:
        def call(self, method, *args):
            # No introspection: that's a call of its own, with no timeout,
            # and every signature used here is spelled out above.
            obj = bus.get_object(KWIN_SERVICE, KWIN_SCRIPTING_PATH, introspect=False)
            # A frozen KWin would hold each call 25 s, dbus-python's default.
            kwargs = {"dbus_interface": KWIN_SCRIPTING_INTERFACE, "timeout": DBUS_TIMEOUT_S}
            if method in signatures:
                kwargs["signature"] = signatures[method]
            return getattr(obj, method)(*args, **kwargs)

    return _KWinBus()


def load_and_start(bus, path, plugin_name) -> None:
    """Load a script file into KWin and start it. Raises if KWin refuses.

    Started with Scripting.start(), which runs every loaded script that isn't
    running yet, NOT with run() on /Scripting/Script<id>. KWin numbers a new
    script by how many are loaded (scripts.size()), so after an unload a new
    script can get the number of one still loaded. Its D-Bus object then fails
    to register and run() starts the other script instead, so with TuxTalk's
    two scripts the focus script could load after a tray restart and never
    run. start() skips scripts already running, so it is safe to call for one
    new script.
    """
    script_id = bus.call("loadScript", path, plugin_name)
    if int(script_id) < 0:
        # -1: a script by this name is still loaded (the unload hadn't landed).
        raise RuntimeError(f"KWin already has a script named {plugin_name}")
    bus.call("start")


def should_provide() -> bool:
    """Whether this desktop needs us to report focus.

    GNOME is excluded deliberately: its extension already writes the same cache,
    and two writers would race each other for no gain.
    """
    return desktop_detect.get_desktop_environment() == "kde"


def _write_script() -> str:
    """Write the script to script_path() and return that path."""
    path = script_path()
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(build_script())
    return path


def start(bus) -> bool:
    """Load the focus reporter into KWin. True when it is running.

    *bus* is a small caller-supplied shim with .call(method, *args) so the
    D-Bus plumbing stays testable and this module stays import-safe without
    dbus-python present.
    """
    if bus is None or not should_provide():
        return False

    try:
        path = _write_script()
    except Exception as e:
        logger.warning(f"Could not write the KWin focus script: {e}")
        return False

    # KWin keeps scripts loaded across tray restarts, and loading a second
    # copy (or a TalkType-era one) would report every focus change twice.
    for plugin in OLD_SCRIPT_PLUGIN_NAMES + (SCRIPT_PLUGIN_NAME,):
        try:
            bus.call("unloadScript", plugin)
        except Exception as e:      # KWin didn't answer; loading says whether it's there
            logger.info(f"Could not unload a previous KWin focus script {plugin}: {e}")

    try:
        load_and_start(bus, path, SCRIPT_PLUGIN_NAME)
    except Exception as e:
        logger.warning(f"Could not load the KWin focus script: {e}")
        return False

    logger.info("KWin focus reporter loaded; terminal paste detection is active")
    return True


def stop(bus) -> None:
    """Unload the reporter. Never raises — this runs on the quit path."""
    if bus is None:
        return
    for plugin in (SCRIPT_PLUGIN_NAME,) + OLD_SCRIPT_PLUGIN_NAMES:
        try:
            bus.call("unloadScript", plugin)
        except Exception as e:      # the quit goes on; the next start unloads it first
            logger.info(f"Could not unload the KWin focus script {plugin}: {e}")
