"""Snap, centre, show the desktop, switch desktops and move windows between
desktops and screens on KDE Plasma 6, for the voice commands "snap left",
"go to desktop two" and so on.

Snapping, centring, moving a window to a desktop or screen and the overview
are KWin's own global shortcuts, called by name over kglobalaccel: they act
on the active window exactly as the user's own Meta+arrow keys do, and
follow whatever the user set up, with no key pressed. Showing the desktop
and switching desktops are plain methods of org.kde.KWin.

invokeShortcut answers nothing, so it can't say there was no second screen
to move a window to, and KWin has no D-Bus call that counts screens. A
small look-only KWin script counts them (has_other_screen).

The mouse grid's zoom (desktop_zoom) steps KWin's Zoom effect the same
way, through invoke_shortcut and effect_loaded.

Answers are the strings desktop_actions turns into a spoken-style note:
"done", "no_desktop", "one_desktop", "one_screen", "edge" and "unknown";
"stopped" when act()'s *still_wanted* said no, and said why.
"""
import json
import logging
from collections.abc import Callable

from . import kwin_activate, kwin_focus

log = logging.getLogger(__name__)

KGLOBALACCEL = "org.kde.kglobalaccel"
KWIN = "org.kde.KWin"

# The shortcut names are KWin's own (its kglobalaccel component lists them);
# a name KWin doesn't have does nothing.
SHORTCUTS = {
    "snap left": "Window Quick Tile Left",
    "snap right": "Window Quick Tile Right",
    "snap top": "Window Quick Tile Top",
    "snap bottom": "Window Quick Tile Bottom",
    "snap top left": "Window Quick Tile Top Left",
    "snap top right": "Window Quick Tile Top Right",
    "snap bottom left": "Window Quick Tile Bottom Left",
    "snap bottom right": "Window Quick Tile Bottom Right",
    "center": "Window Move Center",
    "to next desktop": "Window to Next Desktop",
    "to previous desktop": "Window to Previous Desktop",
    "to next screen": "Window to Next Screen",
    "overview": "Overview",
}

# KWin has a "Window to Desktop n" shortcut for each n; only 1 to 9 are ever sent.
_STEP_METHODS = {"next desktop": "nextDesktop", "previous desktop": "previousDesktop"}
_WINDOW_DESKTOP_MOVES = ("to next desktop", "to previous desktop")
_SCREENS_PLUGIN = "tuxtalk-screens"


def _call(path: str, interface: str, method: str, signature: str, args: tuple,
          service: str, timeout: float):
    import dbus
    return dbus.SessionBus().call_blocking(service, path, interface, method, signature, args,
                                           timeout=min(timeout, kwin_focus.DBUS_TIMEOUT_S))


def _kwin(method: str, signature: str = "", args: tuple = (), timeout: float = 3.0):
    return _call("/KWin", KWIN, method, signature, args, KWIN, timeout)


def _property(path: str, interface: str, name: str, timeout: float):
    return _call(path, "org.freedesktop.DBus.Properties", "Get", "ss", (interface, name),
                 KWIN, timeout)


def invoke_shortcut(shortcut: str, timeout: float) -> None:
    """Invoke KWin's global *shortcut* by name, as if its keys were pressed.
    Raises the D-Bus error when kglobalaccel can't be reached."""
    _call("/component/kwin", "org.kde.kglobalaccel.Component", "invokeShortcut", "s",
          (shortcut,), KGLOBALACCEL, timeout)


def effect_loaded(effect: str, timeout: float) -> bool:
    """Whether KWin's *effect* ("zoom", ...) is on. Raises the D-Bus error
    when KWin can't be reached."""
    return bool(_call("/Effects", "org.kde.kwin.Effects", "isEffectLoaded", "s", (effect,),
                      KWIN, timeout))


def _invoke(shortcut: str, timeout: float, still_wanted: Callable[[], bool] | None) -> str:
    """Invoke *shortcut*, unless *still_wanted* says it no longer is: KWin
    may have taken a while to answer the questions asked before it, and a
    window shortcut acts on whichever window has the focus by now."""
    if still_wanted is not None and not still_wanted():
        return "stopped"
    invoke_shortcut(shortcut, timeout)
    return "done"


def _desktop_count(timeout: float) -> int:
    return int(_property("/VirtualDesktopManager", "org.kde.KWin.VirtualDesktopManager",
                         "count", timeout))


def _screens_script(expression: str):
    """The builder kwin_activate.ask wants: a look-only script answering
    *expression* (JavaScript, evaluated in KWin), or Failed if it throws."""
    def build(reply_to: str) -> str:
        reply = json.dumps(reply_to)
        return f"""// Generated by TuxTalk to count screens; looks only, touches nothing.
// Unloaded straight after; safe to delete.
(function () {{
    try {{
        callDBus({reply}, "{kwin_activate.ANSWER_PATH}", "{kwin_activate.ANSWER_INTERFACE}",
                 "Answer", {expression});
    }} catch (e) {{
        callDBus({reply}, "{kwin_activate.ANSWER_PATH}", "{kwin_activate.ANSWER_INTERFACE}",
                 "Failed", String(e));
    }}
}})();
"""
    return build


def has_other_screen(timeout: float) -> bool:
    """Whether there is a second screen, asked of a look-only KWin script.
    No answer in time is never taken for "no": a user with two screens must
    never be told there is one. Raises TimeoutError when KWin doesn't
    answer, and the error when KWin refuses the script or it fails."""
    answer = kwin_activate.ask(_screens_script("workspace.screens.length > 1"),
                               _SCREENS_PLUGIN, kwin_activate.script_path("tuxtalk-screens.js"),
                               timeout)
    if answer is None:
        raise TimeoutError("KWin didn't answer in time")
    return answer


def _show_desktop(timeout: float) -> str:
    showing = bool(_property("/KWin", KWIN, "showingDesktop", timeout))
    _kwin("showDesktop", "b", (not showing,), timeout)
    return "done"


def _switch_to(number: int, timeout: float) -> str:
    return "done" if _kwin("setCurrentDesktop", "i", (number,), timeout) else "no_desktop"


def _step(method: str, timeout: float) -> str:
    """Next or previous desktop; "edge" when the user is already on the last
    (or first) one and KWin doesn't wrap round."""
    before = _kwin("currentDesktop", timeout=timeout)
    _kwin(method, timeout=timeout)
    return "done" if _kwin("currentDesktop", timeout=timeout) != before else "edge"


def act(action: str, number: int | None, timeout: float,
        still_wanted: Callable[[], bool] | None = None) -> str:
    """Do *action* ("snap left", "center", "overview", "to next screen",
    "show desktop", "desktop" or "to desktop" with *number*, "next desktop",
    ...) and answer as the module's docstring says. *timeout* bounds each
    D-Bus call (a next or previous desktop makes four, the most) and the
    screens script's wait. *still_wanted*, if given,
    is asked right before a shortcut is invoked. Raises the D-Bus error
    when KWin or kglobalaccel can't be reached, TimeoutError when the
    screens script isn't answered."""
    if action in SHORTCUTS:
        return _shortcut_action(action, timeout, still_wanted)
    if action == "show desktop":
        return _show_desktop(timeout)
    if action in ("desktop", "to desktop") and number is not None:
        return _numbered_desktop(action, number, timeout, still_wanted)
    if action in _STEP_METHODS:
        return "one_desktop" if _desktop_count(timeout) == 1 else _step(
            _STEP_METHODS[action], timeout)
    return "unknown"


def _shortcut_action(action: str, timeout: float, still_wanted) -> str:
    if action in _WINDOW_DESKTOP_MOVES and _desktop_count(timeout) == 1:
        return "one_desktop"
    if action == "to next screen" and not has_other_screen(timeout):
        return "one_screen"
    return _invoke(SHORTCUTS[action], timeout, still_wanted)


def _numbered_desktop(action: str, number: int, timeout: float, still_wanted) -> str:
    if action == "desktop":
        return _switch_to(number, timeout)
    if not 1 <= number <= min(9, _desktop_count(timeout)):
        return "no_desktop"
    return _invoke(f"Window to Desktop {number}", timeout, still_wanted)
